export function translate(locale: Locale, key: string): string {
  key = Object.hasOwn(statusCopy, key) ? statusCopy[key] : key;
  if (locale === 'zh-TW') return key;
  if (Object.hasOwn(english, key)) return locale === 'en' ? english[key as MessageKey] : vietnamese[key as MessageKey];
  if (Object.hasOwn(legacyMessages, key)) return legacyMessages[key][locale === 'en' ? 0 : 1];
  if (Object.hasOwn(apiMessages, key)) return apiMessages[key][locale === 'en' ? 0 : 1];
  return Object.hasOwn(workspaceMessages, key) ? workspaceMessages[key][locale === 'en' ? 0 : 1] : key;
}

const errorSourceKeys = new Map<string, string>();
for (const key of [...Object.keys(workspaceMessages), ...Object.keys(apiMessages), ...Object.keys(legacyMessages), ...Object.keys(english)]) {
  for (const locale of ['en', 'vi'] as const) errorSourceKeys.set(translate(locale, key), key);
}

export function translateError(locale: Locale, message: string): string {
  message = errorSourceKeys.get(message) ?? message;
  if (Object.hasOwn(english, message) || Object.hasOwn(workspaceMessages, message) || Object.hasOwn(legacyMessages, message) || Object.hasOwn(apiMessages, message)) return translate(locale, message);
  // Only already-public errors reach here. Never machine-translate or expose provider diagnostics.
  return locale === 'zh-TW' && /\p{Script=Han}/u.test(message) ? message :
    translate(locale, '操作未完成，請確認資料後重試。');
}
